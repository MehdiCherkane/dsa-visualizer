const numberParam = (
  name: string,
  label: string,
  defaultValue: number,
  target = false,
): ParamDef => ({
  name,
  kind: 'number',
  label,
  defaultValue,
  ...(target ? { target: true } : {}),
})

const textParam = (name: string, label: string, defaultValue: string): ParamDef => ({
  name,
  kind: 'text',
  label,
  defaultValue,
})

